/* USER CODE BEGIN 4 */
void Send_Task(void *arg) {
	DHT11_Data_t data;
	uint8_t temp, hum;
	for (;;) {
	//	printf("sender starts\n\r");
		event_count++;
		Read_Temp_Hum(&data);
		temp = data.temperature;
		hum = data.humidity;
	//	printf("sender ends\n\r");
		xSemaphoreTake(My_Semaphore, portMAX_DELAY);
		xQueueSend(MY_Queue, &temp, portMAX_DELAY);
		xQueueSend(MY_Queue, &hum, portMAX_DELAY);
//		printf("sender last\n\r");
	}
}

void Receive_Task(void *arg) {
	uint8_t temp, hum;
	for (;;) {
//		printf("recv starts\n\r");
		xQueueReceive(MY_Queue, &temp, portMAX_DELAY);
		xQueueReceive(MY_Queue, &hum, portMAX_DELAY);
		xSemaphoreTake(My_mutex, portMAX_DELAY);
		printf("Temp->%d Hum->%d\n\r", temp, hum);
		xSemaphoreGive(My_mutex);
	//	printf("recv ends\n\r");
	}
}

